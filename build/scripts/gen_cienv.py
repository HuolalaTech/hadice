#!/usr/bin/env python3
"""Bake selected `.env.ci` fields into backend/cienv_generated.go.

Never copies `.env.ci` into the app bundle. Process env overrides file values.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "backend" / "cienv_generated.go"
ENV_FILE = ROOT / ".env.ci"

KEYS = [
    "POSTHOG_API_KEY",
    "POSTHOG_CAPTURE_URL",
    "VITE_POSTHOG_KEY",
    "VITE_POSTHOG_HOST",
    "VITE_UPDATE_CHECK_URL",
    "VITE_DOCS_URL",
]


def parse_env(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    if not path.is_file():
        return out
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[7:].strip()
        eq = line.find("=")
        if eq <= 0:
            continue
        key = line[:eq].strip()
        val = line[eq + 1 :].strip()
        if len(val) >= 2 and val[0] == val[-1] and val[0] in "\"'":
            val = val[1:-1]
        if key:
            out[key] = val
    return out


def main() -> None:
    file_vals = parse_env(ENV_FILE)
    values: dict[str, str] = {}
    for key in KEYS:
        env_val = os.environ.get(key)
        if env_val is not None and env_val.strip() != "":
            values[key] = env_val.strip()
        else:
            values[key] = file_vals.get(key, "").strip()

    width = max(len(k) for k in KEYS)
    lines = [
        "// Code generated by generate:cienv task. DO NOT EDIT.",
        "// Built from `.env.ci` at package/build time; open-source default is empty.",
        "package backend",
        "",
        "// embeddedCIEnv holds private CI defaults baked into the binary at build time.",
        "// Runtime process env and a local `.env.ci` (dev) still take precedence when set.",
        "var embeddedCIEnv = map[string]string{",
    ]
    for key in KEYS:
        pad = " " * (width - len(key))
        lines.append(f"\t{json.dumps(key)}{pad}: {json.dumps(values[key])},")
    lines.append("}")
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    filled = sum(1 for k in KEYS if values[k])
    src = ".env.ci" if ENV_FILE.is_file() else "empty defaults"
    print(f"Wrote {OUT.relative_to(ROOT)} from {src} ({filled}/{len(KEYS)} keys non-empty)")
    if filled:
        print(
            "NOTE: non-empty embed values are for local/release builds only; "
            "do not commit secrets. Reset with empty .env.ci before open-source pushes."
        )


if __name__ == "__main__":
    main()
