// Command gen_version reads info.version from the Wails build configuration.
// By default it generates backend/version.go and synchronises the macOS plists.
// With --print it only writes the version to stdout for use by Task variables.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"os"
	"regexp"
	"strings"
)

var semanticVersion = regexp.MustCompile(`^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$`)

func main() {
	printOnly := flag.Bool("print", false, "print info.version without changing files")
	flag.Parse()

	version, err := readInfoVersion("build/config.yml")
	if err != nil {
		fatal(err)
	}

	if *printOnly {
		fmt.Println(version)
		return
	}

	generated := fmt.Sprintf("// Code generated by generate:version task. DO NOT EDIT.\npackage backend\n\nconst generatedAppVersion = %q\n", version)
	if fileUsesCRLF("backend/version.go") {
		generated = strings.ReplaceAll(generated, "\n", "\r\n")
	}
	if err := writeIfChanged("backend/version.go", []byte(generated)); err != nil {
		fatal(fmt.Errorf("write backend/version.go: %w", err))
	}

	if err := syncPlist("build/darwin/Info.plist", version); err != nil {
		fatal(err)
	}
	if err := syncPlist("build/darwin/Info.dev.plist", version+"-dev"); err != nil {
		fatal(err)
	}

	fmt.Printf("Version %s written to backend/version.go and synced to the macOS plists\n", version)
}

func readInfoVersion(path string) (string, error) {
	file, err := os.Open(path)
	if err != nil {
		return "", fmt.Errorf("open %s: %w", path, err)
	}
	defer file.Close()

	inInfo := false
	infoIndent := 0
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := scanner.Text()
		trimmed := strings.TrimSpace(line)
		if trimmed == "" || strings.HasPrefix(trimmed, "#") {
			continue
		}

		indent := len(line) - len(strings.TrimLeft(line, " \t"))
		if !inInfo {
			if trimmed == "info:" {
				inInfo = true
				infoIndent = indent
			}
			continue
		}

		if indent <= infoIndent {
			break
		}
		key, value, found := strings.Cut(trimmed, ":")
		if !found || strings.TrimSpace(key) != "version" {
			continue
		}
		version := strings.Trim(strings.TrimSpace(value), `"'`)
		if !semanticVersion.MatchString(version) {
			return "", fmt.Errorf("invalid info.version %q in %s", version, path)
		}
		return version, nil
	}
	if err := scanner.Err(); err != nil {
		return "", fmt.Errorf("read %s: %w", path, err)
	}
	return "", fmt.Errorf("cannot read info.version from %s", path)
}

func syncPlist(path, version string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("read %s: %w", path, err)
	}

	pattern := regexp.MustCompile(`(<key>(?:CFBundleVersion|CFBundleShortVersionString)</key>\r?\n[ \t]*<string>)[^<]*(</string>)`)
	updated := pattern.ReplaceAll(data, []byte(`${1}`+version+`${2}`))
	if bytes.Equal(updated, data) && !pattern.Match(data) {
		return fmt.Errorf("version keys not found in %s", path)
	}
	if err := writeIfChanged(path, updated); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}

func writeIfChanged(path string, content []byte) error {
	existing, err := os.ReadFile(path)
	if err == nil && bytes.Equal(existing, content) {
		return nil
	}
	return os.WriteFile(path, content, 0o644)
}

func fileUsesCRLF(path string) bool {
	content, err := os.ReadFile(path)
	return err == nil && bytes.Contains(content, []byte("\r\n"))
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "Error:", err)
	os.Exit(1)
}
